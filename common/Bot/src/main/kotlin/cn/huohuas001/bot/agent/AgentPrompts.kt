/**
 * Agent 相关提示词的内置默认值。
 *
 * 这些文本同时也是 config.yml 里对应配置项的初始内容：配置文件里的值优先，
 * 留空或缺失时回落到这里。两处内容保持一致，改动请同步修改。
 */
object AgentPrompts {

    /**
     * 思考引导提示词。
     *
     * 给**不具备原生推理能力**的模型用：要求它把分析过程写进 `[思考]` 标签里，
     * 程序再把标签内的内容取出来当作思考过程（写日志或按配置发到群里），
     * 标签之外的正文才是给用户看的最终答复。
     * 原生推理模型本身就会产出思考过程，再加这段引导只会让它重复思考，建议关闭。
     *
     * 用 `[思考]` 而非 `<think>`：部分厂商的接口会把 `<think>` 当特殊标记剥掉，导致
     * 思考块直接消失（AgnesAI 实测如此），方括号标记不受影响。
     */
    const val THINK_GUIDE = """
你在处理 Minecraft 服务器管理任务。请严格按下面的方式工作：

1. 先在 `[思考]` 与 `[/思考]` 之间完成分析，再输出最终答复。`[思考]` 区块内的内容不会展示给用户。
2. 分析时依次覆盖以下几项，逐条写清结论，不要跳过：
   - 任务理解：用户真正想达成的最终结果是什么，其中哪些是必须满足的硬性要求，哪些只是偏好。
   - 信息盘点：已经掌握的事实（服务器与插件信息、工具返回结果、用户给的数据），以及还缺哪些信息才能动手。
   - 方案拆解：把任务拆成可执行步骤，写明每一步用哪个工具、参数怎么填；需要执行服务器命令的步骤要写出命令原文。
   - 风险校验：命令是否超出你的权限、是否可能误伤玩家或丢失数据、是否命中命令黑名单、执行范围是否过宽。
   - 自检：结论有没有和已知事实矛盾；数字、坐标、物品 ID、数量、玩家名有没有抄错；方案里的每一步是否都真的调用了工具。
3. `[思考]` 里不要复述大段工具输出原文，只写判断和结论；分析长度与任务复杂度成正比，简单任务不要长篇大论。
4. `[/思考]` 之后直接输出给用户看的最终答复：中文、简洁、只讲结果和必要的操作说明，不要出现"让我想想""首先我需要分析"这类过程性表述。
5. 缺少关键信息时不要猜测：说明缺什么、能提供哪些选项，让用户来定。
"""

    /**
     * 上下文压缩提示词。
     *
     * 把整段对话压成一份"接手即可继续工作"的摘要。摘要会直接替换原上下文，
     * 丢掉的东西 AI 就再也看不到了，所以宁可多留细节也不要写成空泛概括。
     * 文中的 `{target}` 会被替换成配置的压缩目标 token 数。
     */
    const val CONTEXT_COMPRESS = """
你正在为 Minecraft 服务器管理 AI 助手压缩一段对话上下文。压缩后的摘要会**替代**原对话继续工作，因此任何丢失的细节都等于让助手从头再犯一次错。

请输出一份结构化摘要，严格使用下面这些标题，每个标题下最多 5 条：

## 任务目标
用户最终想达成什么，以及目前已经完成到哪一步。

## 关键事实
从对话和工具结果中已经确认的事实，逐条列出。数字、坐标、物品 ID、数量、玩家名、openid、群号、命令原文必须逐字保留，不要改写、不要换算、不要四舍五入。

## 已执行的操作
已经执行过的服务器命令或改动，以及结果（成功或失败、报错信息要点）。命令用代码格式原样写出。

## 决策与理由
做过的取舍及原因，包括用户明确表达的偏好与禁止事项（例如"不要动某个区块""以后先问再执行"）。

## 待办与未解决问题
还没做的事、需要用户回答的问题、悬而未决的疑点。

## 踩过的坑
失败的尝试、报错信息、被拒绝的操作，以及由此得出的"不要再这么做"的结论。

## 实体对照
openid / member_openid / QQ 昵称 / MC 玩家名 / group_openid 之间的对应关系。

写作要求：
- 只写原对话中真实出现过的内容，不要推测、不要补充、不确定的条目直接省略。
- 面向"接手继续干活的助手"写作，不要写成给人看的汇报。
- 删掉寒暄、重复确认、致谢等没有信息量的内容。
- 摘要总长度控制在 {target} token 以内。
"""
}
